import fs from 'node:fs';
import path from 'node:path';

const siteKey = String(process.env.FIREBASE_APP_CHECK_SITE_KEY || '').trim();
const destination = path.resolve('public/firebase-app-check-config.js');
const contents = `/* Generated by npm run build:site; do not commit this file. */\n` +
  `window.FIREBASE_APP_CHECK_SITE_KEY = ${JSON.stringify(siteKey)};\n`;

fs.mkdirSync(path.dirname(destination), { recursive: true });
fs.writeFileSync(destination, contents, 'utf8');

if (siteKey) {
  console.log('Firebase App Check runtime configuration generated.');
} else {
  console.log('Firebase App Check runtime configuration generated without a site key.');
}
